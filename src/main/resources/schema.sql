-- H2 本地文件数据库初始化脚本。
-- 印刷厂生产管理：机台台账、印单全量记录、印单追溯链（作废走反向记录）。
-- 约定：所有业务表带审计列 request_no / create_by / operator_name / create_time /
--       update_by / update_time / version / deleted；删除只打标记（deleted=1），不物理删除。

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('print-1', '机台台账、印单全量记录、印单反向记录追溯链');

-- ============ 机台台账 ============
CREATE TABLE IF NOT EXISTS t_machine (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code    VARCHAR(64)  NOT NULL,          -- 机台号（业务唯一键）
    machine_name    VARCHAR(128) NOT NULL,          -- 机台名称
    machine_type    VARCHAR(64),                    -- 机台类型（如胶印/数码）
    max_sheet_size  VARCHAR(64),                    -- 最大印刷幅面
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE 启用 / DISABLED 停用
    remark          VARCHAR(500),
    -- 审计列
    request_no      VARCHAR(64),                    -- 请求号
    create_by       BIGINT,                         -- 操作人ID
    operator_name   VARCHAR(64),                    -- 操作人姓名（冗余，便于追溯）
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP,
    version         INT NOT NULL DEFAULT 0,         -- 乐观锁版本
    deleted         INT NOT NULL DEFAULT 0          -- 删除标记：0 正常 1 已删除
);

-- 机台号唯一（全量留痕：删除只打标记，机台号不释放、不重建同号）
CREATE UNIQUE INDEX IF NOT EXISTS uk_machine_code ON t_machine (machine_code);
CREATE INDEX IF NOT EXISTS idx_machine_status ON t_machine (status);

-- ============ 印单全量记录 ============
CREATE TABLE IF NOT EXISTS t_print_order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no            VARCHAR(64)  NOT NULL,      -- 印单号（业务唯一键）
    customer_name       VARCHAR(128),               -- 客户
    product_name        VARCHAR(128),               -- 印品名称
    machine_id          BIGINT,                     -- 排产机台（可空，台账关联）
    print_date          DATE,                       -- 生产日期（组合检索用）
    -- 用纸估算输入
    print_qty           BIGINT,                     -- 印数（成品份数）
    kai                 INT,                        -- 开数：一张全张开多少个成品（如 16）
    paper_length_mm     INT,                        -- 全张纸长 mm
    paper_width_mm      INT,                        -- 全张纸宽 mm
    gsm                 INT,                        -- 克重 g/m2
    waste_rate          DECIMAL(8,4),               -- 损耗率
    add_rate            DECIMAL(8,4),               -- 加放率
    -- 用纸估算结果：理论 / 损耗 / 加放 分列
    base_sheets         BIGINT,                     -- 理论用纸（全张纸）= CEIL(印数/开数)
    waste_sheets        BIGINT,                     -- 损耗用纸（全张纸）单列
    add_sheets          BIGINT,                     -- 加放用纸（全张纸）单列
    total_sheets        BIGINT,                     -- 合计全张纸 = 理论+损耗+加放
    paper_weight_kg     DECIMAL(12,3),              -- 用纸量 kg = 合计张数 × 单张面积 × 克重 / 1000
    status              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE 有效 / VOID 已作废
    remark              VARCHAR(500),
    -- 审计列
    request_no          VARCHAR(64),
    create_by           BIGINT,
    operator_name       VARCHAR(64),
    create_time         TIMESTAMP,
    update_by           BIGINT,
    update_time         TIMESTAMP,
    version             INT NOT NULL DEFAULT 0,
    deleted             INT NOT NULL DEFAULT 0
);

-- 印单号唯一：同一印单号重复建档直接拒绝（全量记录，软删除后号仍不释放）
CREATE UNIQUE INDEX IF NOT EXISTS uk_print_order_no ON t_print_order (order_no);
CREATE INDEX IF NOT EXISTS idx_print_order_date ON t_print_order (print_date);
CREATE INDEX IF NOT EXISTS idx_print_order_status ON t_print_order (status);

-- ============ 印单追溯链：建档正向记录 + 作废反向记录 ============
CREATE TABLE IF NOT EXISTS t_print_order_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL,                -- 关联印单
    order_no        VARCHAR(64) NOT NULL,           -- 冗余印单号，印单删除后链仍可读
    record_type     VARCHAR(16) NOT NULL,           -- CREATE 建档 / VOID 作废（反向记录）
    reverse_of_id   BIGINT,                          -- 反向记录指向的原记录ID（VOID -> CREATE）
    reason          VARCHAR(500),                    -- 作废原因 / 备注
    -- 审计列
    request_no      VARCHAR(64),
    create_by       BIGINT,
    operator_name   VARCHAR(64),
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP,
    version         INT NOT NULL DEFAULT 0,
    deleted         INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_po_record_order ON t_print_order_record (order_id);
CREATE INDEX IF NOT EXISTS idx_po_record_no ON t_print_order_record (order_no);
